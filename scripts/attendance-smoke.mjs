async function login(user, password, role, fakeFrame) {
  const ctx = await browser.newContext();
  if (fakeFrame) await ctx.addInitScript((url) => {
    Object.defineProperty(navigator.mediaDevices, 'getUserMedia', { value: async () => {
      const image = new Image(); image.src = url; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
      const pen = canvas.getContext('2d');
      let frame = image;
      const stream = canvas.captureStream(15);
      window.__mmaTestCamera = stream;
      window.__mmaReplaceTestFrame = async (src) => { const next = new Image(); next.src = src; await next.decode(); frame = next; };
      const pump = setInterval(() => { if (stream.active) pen.drawImage(frame, 0, 0, canvas.width, canvas.height); else clearInterval(pump); }, 50);
      return stream;
    } });
  }, `data:image/jpeg;base64,${fakeFrame.toString('base64')}`);
  const page = await ctx.newPage(); recordIssues(page);
  await visit(page, '/login');
  await page.getByLabel('Student ID or username').fill(user);
  await page.locator('input[name=password]').fill(password);
  await Promise.all([page.waitForURL(`${origin}/${role}`), page.getByRole('button', { name: 'Sign in', exact: true }).click()]);
  const cookie = (await ctx.cookies()).find((x) => x.name === 'mma_session');
  assert(cookie?.httpOnly);
  return { ctx, page, headers: { Origin: origin, 'X-MMA-Request': '1', 'X-MMA-CSRF': createHash('sha256').update(`mma-csrf-v1:${cookie.value}`).digest('hex') } };
}
async function act(who, action, data, expected = 200) {
  const res = await who.ctx.request.post(`${origin}/api/workspace/${action}`, { headers: who.headers, data });
  const body = await res.json();
  assert.equal(res.status(), expected, `${action}: ${JSON.stringify({ message: body.message, error: body.error })}`);
  return body;
}
async function face(who, action, image, params, expected = 200) {
  const res = await who.ctx.request.post(`${origin}/api/workspace/${action}`, { headers: who.headers, multipart: { ...params, frame: { name: 'test-frame.jpg', mimeType: 'image/jpeg', buffer: image } } });
  const body = await res.json();
  assert.equal(res.status(), expected, `${action}: ${body.error || body.message}`);
  return body;
}
